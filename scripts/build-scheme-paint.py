#!/usr/bin/env python3
"""Builds the paint rules of the W3CSS color scheme files from
scripts/scheme-paint-rules.json, the one place that holds those rules.

Usage (from the theme root):
  python3 -I scripts/build-scheme-paint.py              write the scheme files
  python3 -I scripts/build-scheme-paint.py --check      exit 1 on drift or on a
                                                        revert-layer fallback
  python3 -I scripts/build-scheme-paint.py --self-test  prove the checks go red

Why: a rule written as prop: var(--token, revert-layer) does not "not exist"
when a scheme leaves the token out. revert-layer rolls the whole cascade layer
back for that property on that element, so it also wipes every earlier rule of
the same layer, from any file. So a scheme file carries only the rules whose
token it sets, as var(--token) with no fallback: a rule exists for a scheme
exactly when that scheme sets its token.

The data holds rule groups. Each group names a library; every scheme library
that depends on it (libraries/w3css-libraries.json) gets the group's rules
whose tokens its file sets, appended after its tokens in the same layers, with
the same selectors and in the same order. Each rule is one selector list and
one or more [property, token] pairs; a pair whose token the file does not set
is left out, and a rule with no pair left is left out.

--check also fails on any var(..., revert-layer) under css/predefined/. It
prints the file and rule counts, so a run that read nothing cannot pass.
Standard library only.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "scripts", "scheme-paint-rules.json")
LIBS = os.path.join(ROOT, "libraries", "w3css-libraries.json")
PREDEFINED = os.path.join(ROOT, "css", "predefined")
OWNER = "drupal8_w3css_theme"
MARK = "/* Paint rules: generated by scripts/build-scheme-paint.py"
INTRO = (
    MARK + " from\n"
    " * scripts/scheme-paint-rules.json, only for the tokens this file sets.\n"
    " * Do not edit by hand: edit the data and run the script. */\n"
)
OLD_HEAD = (
    "Tokens only, in w3css.schemes. The rules that read them are in\n"
    " * css/predefined/w3css-scheme-custom-paint.css."
)
NEW_HEAD = (
    "Tokens in w3css.schemes, then the paint rules for the tokens this file\n"
    " * sets, generated by scripts/build-scheme-paint.py."
)
TOKEN_SET = re.compile(r"(--[A-Za-z0-9_-]+)\s*:")
REVERT_FALLBACK = re.compile(r"var\([^;{}]*?revert-layer")


def tokens_set(text):
    """Return the custom properties a scheme file sets (its own part only)."""
    return set(TOKEN_SET.findall(text.split(MARK)[0]))


def render(rules, tokens):
    """Return (css, rule count) for the rules whose tokens are in tokens."""
    out = []
    count = 0
    layer = media = None
    for rule in rules:
        decls = [(p, t) for p, t in rule["decls"] if t in tokens]
        if not decls:
            continue
        count += 1
        new_layer = rule["layer"] != layer
        new_media = new_layer or rule.get("media") != media
        if new_media and media is not None:
            out.append("  }\n")
        if new_layer:
            if layer is not None:
                out.append("}\n\n")
            out.append(f"@layer {rule['layer']} {{\n")
        if not out[-1].endswith("{\n"):
            out.append("\n")
        layer = rule["layer"]
        if new_media:
            media = rule.get("media")
            if media is not None:
                out.append(f"  @media {media} {{\n")
        pad = "    " if media is not None else "  "
        out.append(",\n".join(pad + s for s in rule["selectors"]) + " {\n")
        for p, t in decls:
            out.append(f"{pad}  {p}: var({t});\n")
        out.append(pad + "}\n")
    if media is not None:
        out.append("  }\n")
    if layer is not None:
        out.append("}\n")
    return "".join(out), count


def build(text, rules):
    """Return (new file text, rule count) for one scheme file."""
    head = text.split(MARK)[0].rstrip() + "\n"
    head = head.replace(OLD_HEAD, NEW_HEAD)
    css, count = render(rules, tokens_set(text))
    if count:
        head += "\n" + INTRO + "\n" + css
    return head, count


def targets(data):
    """Yield (group name, rules, file path) for every scheme file to build."""
    libs = json.load(open(LIBS, encoding="utf-8"))["libraries"]
    seen = {}
    for name, group in data["groups"].items():
        dep = f"{OWNER}/{group['library']}"
        for lib in libs:
            if dep not in lib.get("dependencies", []):
                continue
            paths = [c["path"] for c in lib.get("css", {}).get("theme", [])]
            if len(paths) != 1:
                raise ValueError(f"{lib['id']}: expected one theme CSS file, got {paths}")
            if paths[0] in seen:
                raise ValueError(f"{paths[0]} is in two groups: {seen[paths[0]]}, {name}")
            seen[paths[0]] = name
            yield name, group["rules"], os.path.join(ROOT, paths[0])


def revert_hits(rel, text):
    """Return one message per var(..., revert-layer) in text."""
    hits = []
    for m in REVERT_FALLBACK.finditer(re.sub(r"/\*.*?\*/", lambda c: re.sub(r"[^\n]", " ", c.group()), text, flags=re.S)):
        line = text.count("\n", 0, m.start()) + 1
        hits.append(f"RL {rel}:{line} var() falls back to revert-layer, which wipes the whole layer for that property")
    return hits


def scan_predefined(folder):
    out = []
    for f in sorted(os.listdir(folder)):
        if f.endswith(".css"):
            out += revert_hits(os.path.join("css", "predefined", f), open(os.path.join(folder, f), encoding="utf-8").read())
    return out


def self_test():
    fails = 0
    rules = [
        {"layer": "w3css.base", "selectors": ["body"], "decls": [["color", "--a"], ["background-color", "--b"]]},
        {"layer": "w3css.schemes", "media": "(max-width: 1px)", "selectors": [".x"], "decls": [["padding", "--c"]]},
    ]
    cases = [
        (revert_hits("x.css", ".a { color: var(--t, revert-layer); }") != [], "revert-layer fallback is reported"),
        (revert_hits("x.css", ".a { color: var(--t); }\n/* var(--t, revert-layer) */") == [], "plain var and comments pass"),
        ("var(--a)" in render(rules, {"--a"})[0] and "--b" not in render(rules, {"--a"})[0], "only set tokens are painted"),
        (render(rules, set()) == ("", 0), "no token, no rule"),
        ("@media (max-width: 1px)" in render(rules, {"--c"})[0], "media kept"),
        (build("x\n", rules)[0] == "x\n", "file without tokens unchanged"),
        (build(build(":root { --a: red; }\n", rules)[0], rules) == build(":root { --a: red; }\n", rules), "build is idempotent"),
    ]
    for ok, what in cases:
        if not ok:
            fails += 1
            print(f"SELF-TEST FAIL: {what}")
    print(f"self-test: {len(cases)} cases, {fails} failures")
    return 1 if fails else 0


def main():
    args = sys.argv[1:]
    if args == ["--self-test"]:
        return self_test()
    check = args == ["--check"]
    if args and not check:
        print(__doc__)
        return 2
    data = json.load(open(DATA, encoding="utf-8"))
    problems = []
    files = rules_out = 0
    for name, rules, path in targets(data):
        text = open(path, encoding="utf-8").read()
        new, count = build(text, rules)
        files += 1
        rules_out += count
        rel = os.path.relpath(path, ROOT)
        if new != text:
            if check:
                problems.append(f"DRIFT {rel} differs from what the script writes")
            else:
                open(path, "w", encoding="utf-8").write(new)
                print(f"wrote {rel} ({name}, {count} rules)")
    if check:
        problems += scan_predefined(PREDEFINED)
    for p in problems:
        print(p)
    print(f"build-scheme-paint: {files} scheme files, {rules_out} rules, {len(problems)} problems")
    if files == 0 or rules_out == 0:
        print("build-scheme-paint: read nothing, failing")
        return 1
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
