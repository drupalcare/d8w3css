#!/usr/bin/env python3
"""Builds drupal8_w3css_theme.libraries.yml and src/SchemeLibraries.php from
libraries/w3css-libraries.json, the one place that holds every library.

Usage (from the theme root):
  python3 -I scripts/build-libraries.py           write both generated files
  python3 -I scripts/build-libraries.py --check   exit 1 when a file differs from the data

The data file lists every library once (id, css and js files with their
options, dependencies). A library with a "was" value also produces a
deprecated alias under the old id, unless "alias" is false. "also_was" lists
more old ids that each get a deprecated alias of the library (several released
libraries folded into one). A library with a
"stored" value is a color scheme: the setting value that selects it
(color_scheme.predefined). Standard library only.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "libraries", "w3css-libraries.json")
YML = os.path.join(ROOT, "drupal8_w3css_theme.libraries.yml")
PHP = os.path.join(ROOT, "src", "SchemeLibraries.php")
OWNER = "drupal8_w3css_theme"
DEPRECATED = (
    'The %library_id% asset library is deprecated in w3css 3.0.0 and is removed '
    'from w3css 4.0.0. Use {owner}/{new} instead.'
)
HEAD_YML = (
    "# Generated by scripts/build-libraries.py from libraries/w3css-libraries.json.\n"
    "# Do not edit this file: edit the data file and run the script.\n"
)


def scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return str(v)


def flow(o):
    if not o:
        return "{ }"
    parts = []
    for k, v in o.items():
        parts.append(f"{k}: {flow(v) if isinstance(v, dict) else scalar(v)}")
    return "{ " + ", ".join(parts) + " }"


def key(path):
    return "'" + path + "'" if ("?" in path or ";" in path) else path


def meta_lines(v, indent):
    out = []
    for k, x in v.items():
        if isinstance(x, dict):
            out.append(f"{indent}{k}:")
            out += meta_lines(x, indent + "  ")
        else:
            out.append(f"{indent}{k}: {scalar(x)}")
    return out


def entry_lines(entries, indent):
    out = []
    for e in entries:
        for c in e.get("pre", []):
            out.append((indent + c) if c else "")
        out.append(f"{indent}{key(e['path'])}: {flow(e.get('options', {}))}")
    return out


def build_yml(data):
    out = [HEAD_YML.rstrip("\n"), ""]
    for lib in data["libraries"]:
        if lib.get("gap", True) is False and out[-1] == "":
            out.pop()
        for c in lib.get("pre", []):
            out.append(c)
        out.append(f"{lib['id']}:")
        out += meta_lines(lib.get("meta", {}), "  ")
        if lib.get("css"):
            out.append("  css:")
            for group, entries in lib["css"].items():
                out.append(f"    {group}:")
                out += entry_lines(entries, "      ")
        if lib.get("js"):
            out.append("  js:")
            out += entry_lines(lib["js"], "    ")
        if lib.get("dependencies"):
            out.append("  dependencies:")
            out += [f"    - {d}" for d in lib["dependencies"]]
        out.append("")
    aliases = [(x["was"], x["id"]) for x in data["libraries"] if x.get("was") and x.get("alias", True)]
    aliases += [(old, x["id"]) for x in data["libraries"] for old in x.get("also_was", [])]
    multi = data.get("multi_aliases", [])
    if aliases or multi:
        out.append("# Deprecated aliases: the library ids before the 3.0.0 renames. They hold no files, so")
        out.append("# a libraries-override of an old id has nothing to override: use the new id.")
        out.append("")
    for old, new in aliases:
        msg = DEPRECATED.format(owner=OWNER, new=new)
        out.append(f"{old}:")
        out.append(f'  deprecated: "{msg}"')
        out.append("  dependencies:")
        out.append(f"    - {OWNER}/{new}")
        out.append("")
    for alias in multi:
        # An old library that was split into one library per file: the alias
        # depends on every part, in the old load order.
        msg = DEPRECATED.split(" Use ")[0].replace("%library_id%", "%library_id%") + (
            " Attach the new per-file libraries instead; this alias loads all of them."
        )
        out.append(f"{alias['was']}:")
        out.append(f'  deprecated: "{msg}"')
        out.append("  dependencies:")
        out += [f"    - {OWNER}/{i}" for i in alias["of"]]
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def build_php(data):
    rows = []
    for lib in data["libraries"]:
        if lib.get("stored"):
            rows.append(f"    '{lib['stored']}' => '{lib['id']}',")
    return (
        "<?php\n\ndeclare(strict_types=1);\n\nnamespace Drupal\\drupal8_w3css_theme;\n\n"
        "// Generated by scripts/build-libraries.py from libraries/w3css-libraries.json.\n"
        "// Do not edit this file: edit the data file and run the script.\n\n"
        "/**\n * The library of each predefined color scheme.\n *\n"
        " * The stored scheme value (color_scheme.predefined) selects the library; the\n"
        " * stored values keep their names, only the library ids are new.\n */\n"
        "final class SchemeLibraries {\n\n"
        "  /**\n   * The library of the default color scheme, used when none is chosen.\n   */\n"
        f"  public const string DEFAULT = '{data['scheme_default']}';\n\n"
        "  /**\n   * The library id of each stored scheme value.\n   */\n"
        "  public const array BY_VALUE = [\n" + "\n".join(rows) + "\n  ];\n\n}\n"
    )


def main():
    with open(DATA, encoding="utf-8") as fh:
        data = json.load(fh)
    ids = [x["id"] for x in data["libraries"]]
    dup = {i for i in ids if ids.count(i) > 1}
    olds = [x["was"] for x in data["libraries"] if x.get("was") and x.get("alias", True)]
    olds += [o for x in data["libraries"] for o in x.get("also_was", [])]
    olds += [x["was"] for x in data.get("multi_aliases", [])]
    clash = (set(olds) & set(ids)) | {o for o in olds if olds.count(o) > 1}
    if dup or clash:
        print("DATA ERROR: duplicate or clashing ids:", sorted(dup | clash))
        return 1
    want = {YML: build_yml(data), PHP: build_php(data)}
    if "--check" in sys.argv:
        bad = 0
        for path, text in want.items():
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if have != text:
                print("DRIFT:", os.path.relpath(path, ROOT), "differs from libraries/w3css-libraries.json; run scripts/build-libraries.py")
                bad = 1
        if not bad:
            print("build-libraries: OK (%d libraries, %d aliases, %d schemes)" % (len(ids), len(olds), sum(1 for x in data["libraries"] if x.get("stored"))))
        return bad
    for path, text in want.items():
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    print("build-libraries: wrote", ", ".join(os.path.relpath(p, ROOT) for p in want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
