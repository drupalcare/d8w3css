# Non-text: the focused field's border against the field's own ground.
BORDERS = [('input focus border', ['input:focus'], ['input', 'select', 'textarea'], 3.0)]


def ratio(a, b):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4

    def lum(c):
        return 0.2126 * ch(c[0]) + 0.7152 * ch(c[1]) + 0.0722 * ch(c[2])
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def hexrgb(h):
    h = h.lstrip('#')
    if len(h) in (3, 4):
        h = ''.join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def parse(text):
    """Flat ordered list of (selectors, {prop: value}); @layer wrappers are looked through."""
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    blocks = []
    for sel, body in re.findall(r'([^{}]+)\{([^{}]*)\}', text):
        if sel.strip().startswith('@'):
            continue
        decls = {}
        for k, v in re.findall(r'([\w-]+)\s*:\s*([^;]+);?', body):
            decls[k] = v.strip()
        sels = []
        for s in re.split(r',(?![^()]*\))', sel):
            sels += expand(' '.join(s.split()))
        blocks.append((sels, decls))
    return blocks


class Sel(str):
    """A selector string that also carries its CSS specificity (ids, classes, elements)."""
    spec = (0, 0, 0)


def specificity(sel):
    """Specificity of a plain selector: ids, classes/attributes/pseudo-classes, elements. :not() counts its
    argument; :where() parts are removed before this is called."""
    sel = re.sub(r'::?[\w-]+\(', ' ', sel.replace(':not(', ' ').replace(':is(', ' '))
    ids = len(re.findall(r'#[\w-]+', sel))
    cls = len(re.findall(r'\.[\w-]+', sel)) + len(re.findall(r'\[[^\]]*\]', sel)) + len(re.findall(r'(?<!:):[\w-]+', sel))
    els = len(re.findall(r'(?:^|[\s>+~(])([a-zA-Z][\w-]*)', sel))
    return (ids, cls, els)


def _sel(text, spec):
    out = Sel(text)
    out.spec = spec
    return out


def expand(sel):
    """:where(A, B) :is(x, y) -> 'A x', 'A y', 'B x', 'B y'; :where(A) rest -> 'A rest'. :where() adds no specificity and :is()
    takes the highest of its arguments, so each expanded selector carries the specificity the browser uses."""
    m = re.match(r'^:where\(([^()]*)\)\s*(.*)$', sel)
    if not m:
        return [_sel(sel, specificity(sel))] if sel else []
    parents, rest = [x.strip() for x in m.group(1).split(',')], m.group(2)
    i = re.match(r'^:is\((.*)\)$', rest)
    if i:
        args = [x.strip() for x in i.group(1).split(',')]
        spec = max(specificity(a) for a in args)
        return [_sel(par + ' ' + a, spec) for par in parents for a in args]
    if not rest:
        return [_sel(par, (0, 0, 0)) for par in parents]
    return [_sel(par + ' ' + rest, specificity(rest)) for par in parents]


class Unresolved(Exception):
    pass


def colors(val, env, depth=0):
    """Every opaque color in a value (gradient stops each count). Raises Unresolved for inherit, images,
    translucent colors or an unknown token, so the caller counts the pair as skipped."""
    if val is None or depth > 8:
        raise Unresolved('depth')
    out = []
    for m in re.finditer(r'#[0-9a-fA-F]{3,8}\b|var\(\s*(--[\w-]+)[^)]*\)|rgba?\(([^)]*)\)|\b[a-z]+\b', val):
        tok = m.group(0)
        if tok.startswith('#'):
            h = tok[1:]
            if len(h) in (4, 8):
                if h[len(h) // 4 * 3:].lower() not in ('f', 'ff'):
                    raise Unresolved('translucent')
                h = h[:len(h) // 4 * 3]
            out.append(hexrgb(h))
        elif m.group(1):
            if m.group(1) not in env:
                raise Unresolved('unset ' + m.group(1))
            out += colors(env[m.group(1)], env, depth + 1)
        elif m.group(2) is not None:
            parts = re.split(r'[\s,/]+', m.group(2).strip())
            if len(parts) > 3 and float(parts[3].rstrip('%')) / (100 if parts[3].endswith('%') else 1) < 1:
                raise Unresolved('translucent')
            out.append(tuple(int(float(p)) for p in parts[:3]))
        elif tok in NAMED and NAMED[tok]:
            out.append(NAMED[tok])
        elif tok in ('inherit', 'transparent', 'currentcolor', 'unset', 'revert', 'initial', 'none'):
            raise Unresolved(tok)
        elif tok in ('rgb', 'rgba', 'var', 'url', 'linear', 'gradient', 'to', 'deg', 'px', 'center', 'no', 'repeat',
                     'cover', 'fixed', 'top', 'bottom', 'left', 'right', 'important'):
            if tok == 'url':
                raise Unresolved('image')
            continue
        else:
            raise Unresolved('unknown word ' + tok)
    if not out:
        raise Unresolved('no color')
    return out


def last(blocks, sels, prop):
    """The cascade winner: highest specificity among matching rules, file order breaks a tie."""
    best, val = None, None
    for order, (rule_sels, decls) in enumerate(blocks):
        if prop not in decls:
            continue
        hits = [getattr(s, 'spec', (0, 0, 0)) for s in rule_sels if s in sels]
        if hits and (best is None or (max(hits), order) >= best):
            best, val = (max(hits), order), decls[prop]
    return val


def first_resolved(blocks, env, sel_lists, prop):
    """The cascade winner among the first selector list that has a rule; then the fallbacks in order."""
    for sels in sel_lists:
        v = last(blocks, sels, prop)
        if v is not None:
            return colors(v, env)
    raise Unresolved('no rule for ' + prop)


def scan(path):
    blocks = parse(open(path).read())
    env = {}
    for sels, decls in blocks:
        if sels == [':root']:
            env.update({k: v for k, v in decls.items() if k.startswith('--')})
    rows, skipped, checked = [], {}, [0]

    def pair(label, fg_lists, bg_lists, need, fg_prop='color', bg_prop='background-color'):
        try:
            fgs = first_resolved(blocks, env, fg_lists, fg_prop)
            bgs = first_resolved(blocks, env, bg_lists, bg_prop)
        except Unresolved as e:
            skipped[label] = str(e)
            return
        checked[0] += 1
        worst, bg = min((ratio(f, b), b) for f in fgs for b in bgs)
        if worst < need:
            fg = min(fgs, key=lambda f: min(ratio(f, b) for b in bgs))
            rows.append((label, '#%02x%02x%02x' % fg, '#%02x%02x%02x' % bg, round(worst, 2), need))

    for spec in SURFACES:
        label, text, ground, fallback, need = spec[:5]
        tfall = spec[5] if len(spec) > 5 else [['body']]
        pair(label, [text] + tfall, [ground, fallback] if fallback else [ground], need)
    for label, border, ground, need in BORDERS:
        pair(label, [border], [ground], need, fg_prop='border-color')
    return rows, checked[0], skipped, len(env)


def run(path):
    results, total, skips, files = {}, 0, {}, 0
    for f in sorted(glob.glob(os.path.join(path, '*.css'))):
        base = os.path.basename(f)
        if base.startswith('w3css-scheme-'):
            continue  # shared rules and keyframes, not a scheme
        rows, n, sk, tokens = scan(f)
        if not tokens:
            continue
        files += 1
        total += n
        results[base[len('w3css-'):-4]] = rows
        skips[base[len('w3css-'):-4]] = sk
    return results, total, skips, files


def keys(results):
    return {f'{n}|{w}|{fg}|{bg}' for n, rows in results.items() for w, fg, bg, _, _ in rows}


def report(results, total, skips, files, baseline, list_only):
    fails = sum(len(r) for r in results.values())
    bad = [k for k, v in results.items() if v]
    for name in sorted(bad):
        print('## ' + name)
        for what, fg, bg, r, need in results[name]:
            mark = '  [baseline]' if f'{name}|{what}|{fg}|{bg}' in baseline else ''
            print(f'  {what:28} {fg} on {bg}  {r}:1 (needs {need}){mark}')
    now = keys(results)
    new, fixed = sorted(now - baseline), sorted(baseline - now)
    nskip = sum(len(s) for s in skips.values())
    print(f'SCHEME CONTRAST: {files} scheme files, {total} pairs checked, {nskip} pairs skipped (unresolvable), '
          f'{fails} failures in {len(bad)} schemes; {len(new)} new, {len(fixed)} baseline entries now passing')
    reasons = {}
    for s in skips.values():
        for label, why in s.items():
            reasons[(label, why)] = reasons.get((label, why), 0) + 1
    for (label, why), n in sorted(reasons.items(), key=lambda x: -x[1])[:12]:
        print(f'  skipped {n:3} x {label}: {why}')
    for k in new:
        print('  NEW  ' + k)
    for k in fixed:
        print('  FIXED (remove from baseline)  ' + k)
    if files < MIN_SCHEMES or total < MIN_PAIRS:
        print(f'FAIL: {files} schemes / {total} pairs (minimum {MIN_SCHEMES} / {MIN_PAIRS}); the scanner is not matching the files')
        return 2
    return 0 if list_only else (1 if new or fixed else 0)


SYNTH = """@layer w3css.schemes {
  :root {
    --t: %s;
    --b: %s;
  }
}
@layer w3css.schemes {
  #w3css-main-region .w3css-page__main > div {
    background-color: var(--b);
    color: var(--t);
  }
}
"""


def self_test(path):
    ok = True
    d = tempfile.mkdtemp()
    try:
        # 1. the ratio math on known values
        math_ok = round(ratio((255, 255, 255), (0, 0, 0)), 2) == 21.0 and round(ratio((119, 119, 119), (255, 255, 255)), 2) == 4.48
        # 2. a planted 1:1 pair is red, a planted 21:1 pair is green (same code path as real files)
        open(os.path.join(d, 'w3css-bad.css'), 'w') .write(SYNTH % ('#808080', '#808080'))
        open(os.path.join(d, 'w3css-good.css'), 'w').write(SYNTH % ('#000000', '#ffffff'))
        rows_bad, n_bad, _, _ = scan(os.path.join(d, 'w3css-bad.css'))
        rows_good, n_good, _, _ = scan(os.path.join(d, 'w3css-good.css'))
        red = any(r[0] == 'main text' and r[3] == 1.0 for r in rows_bad)
        green = n_good > 0 and not rows_good
        # 3. a mutated copy of a real scheme goes red where the real one does not (header text = header ground)
        src = os.path.join(path, 'w3css-ocean-blue.css')
        real_rows, real_n, _, _ = scan(src)
        css = open(src).read()
        mutated = re.sub(r'(--w3css-custom-header-background:)\s*[^;]+;', r'\1 #ffffff;', css)
        mutated = re.sub(r'(--w3css-custom-header-a-text:)\s*[^;]+;', r'\1 #fefefe;', mutated)
        open(os.path.join(d, 'w3css-mutated.css'), 'w').write(mutated)
        mut_rows, mut_n, _, _ = scan(os.path.join(d, 'w3css-mutated.css'))
        mut_red = any(r[0] == 'header link' and r[3] < 1.1 for r in mut_rows) and not any(r[0] == 'header link' for r in real_rows)
        real_results, total, _, files = run(path)
        enough = files >= MIN_SCHEMES and total >= MIN_PAIRS
    finally:
        shutil.rmtree(d)
    print(f'self-test: ratio math 21:1 and 4.48:1 ok={math_ok}; planted 1:1 pair red={red} ({n_bad} pairs); '
          f'planted 21:1 pair green={green} ({n_good} pairs); mutated real scheme header link red={mut_red} '
          f'(real scheme {real_n} pairs, mutated {mut_n}); real scan {files} schemes / {total} pairs enough={enough}')
    ok = math_ok and red and green and mut_red and enough
    return ok


if __name__ == '__main__':
    args = sys.argv[1:]
    flags = [a for a in args if a.startswith('--')]
    pos = [a for a in args if not a.startswith('--')]
    path = pos[0] if pos else os.path.join(os.path.dirname(HERE), 'css', 'predefined')
    if '--self-test' in flags:
        good = self_test(path)
        print('SELF-TEST:', 'OK' if good else 'BROKEN')
        sys.exit(0 if good else 1)
    results, total, skips, files = run(path)
    if '--write-baseline' in flags:
        open(BASELINE, 'w').write('\n'.join(sorted(keys(results))) + '\n')
        print(f'baseline written: {len(keys(results))} entries from {files} schemes, {total} pairs')
        sys.exit(0)
    base = set(l.strip() for l in open(BASELINE) if l.strip()) if os.path.exists(BASELINE) else set()
    sys.exit(report(results, total, skips, files, base, '--list' in flags))
