#!/usr/bin/env python3
"""Scheme contrast gate: the text/ground pairs of every predefined W3CSS color scheme must reach WCAG 2.2 AA.

Modeled on solo/scripts/check-scheme-contrast.py. The W3CSS difference: a scheme file
(css/predefined/w3css-*.css) sets --w3css-custom-* tokens in :root and then carries the paint rules that
read them (generated by build-scheme-paint.py). This script reads BOTH from the file, so it measures
what the theme paints, not the token names:
  1. the :root tokens are resolved (var() chains, hex, rgb(), named colors; gradients count every stop);
  2. for each surface (header, main box, top, bottom, footer region, footer menu, copyright, main nav,
     hover states, w3-theme-* utility classes, inputs) the LAST rule in the file whose selector list names
     that surface decides its text color and its ground, as the cascade does for the layers
     base < schemes < utilities (file order).
Surfaces and the selectors that paint them are in SURFACES below: one table, one place to extend.

Thresholds: text 4.5:1 (1.4.3); the h1 heading 3:1 (large text, 1.4.3: its size needs checking in a browser);
input focus border against its field 3:1 (non-text contrast, 1.4.11).
A pair whose text or ground cannot be resolved (inherit, image, translucent, missing rule) is COUNTED as
skipped and printed in the summary, never silently passed. The gate also fails when too few pairs were checked.

Usage:
  check-scheme-contrast.py [DIR]            report; exit 1 on a failure that is not in the baseline, or a baseline
                                            line that no longer fails (DIR defaults to css/predefined)
  check-scheme-contrast.py --list           print every failure grouped by scheme, exit 0 (palette review)
  check-scheme-contrast.py --write-baseline record today's failures in scheme-contrast-baseline.txt
  check-scheme-contrast.py --self-test      proves the gate goes red on a 1:1 pair and green on a 21:1 pair,
                                            on the ratio math, and on a mutated copy of a real scheme

Known failures sit in scheme-contrast-baseline.txt ('scheme|pair|fg|bg' per line): palettes are the owner's
design, so the gate fails on any NEW failure and never on listed ones. It never edits a palette.
"""
import glob
import os
import re
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
BASELINE = os.path.join(HERE, 'scheme-contrast-baseline.txt')
MIN_SCHEMES = 50
MIN_PAIRS = 500

NAMED = {'white': (255, 255, 255), 'black': (0, 0, 0), 'transparent': None}

