  /**
   * Returns the 3.0 name of an old class or id, or NULL if it has none.
   *
   * Looks in structural, ids, state and generic, in that order, and expands
   * pattern keys.
   */
  public static function newName(string $old): ?string {
    foreach (['structural', 'ids', 'state', 'generic'] as $section) {
      $new = self::lookup(self::MAP[$section], $old);
      if ($new !== NULL) {
        return $new;
      }
    }
    return NULL;
  }

  /**
   * Whether a class is frozen public API.
   */
  public static function isFrozen(string $class): bool {
    return in_array($class, self::MAP['frozen'], TRUE);
  }

  /**
   * Looks a name up in one section, expanding pattern keys.
   *
   * @param array<string, string|null> $rows
   *   One section of the rename table.
   * @param string $old
   *   The old class or id.
   *
   * @return string|null
   *   The new name, or NULL when the section has none for it.
   */
  private static function lookup(array $rows, string $old): ?string {
    if (isset($rows[$old])) {
      return $rows[$old];
    }
    foreach ($rows as $key => $new) {
      if (!str_contains($key, '{')) {
        continue;
      }
      $pattern = '/^' . strtr(preg_quote($key, '/'), [
        '\\{n\\}' => '(?<n>[0-9]+)',
        '\\{menu\\}' => '(?<menu>[a-z0-9-]+)',
        '\\{size\\}' => '(?<size>small|medium|large)',
      ]) . '$/';
      if (preg_match($pattern, $old, $match)) {
        foreach (['n', 'menu', 'size'] as $part) {
          if (isset($match[$part])) {
            $new = str_replace('{' . $part . '}', $match[$part], $new);
          }
        }
        return $new;
      }
    }
    return NULL;
  }

